GLYPH_W = 5
GLYPH_H = 7
DEFAULT_SPACING = 1


def text_width(text: str, scale: int = 1, spacing: int = DEFAULT_SPACING) -> int:
    if not text:
        return 0
    return len(text) * (GLYPH_W * scale + spacing * scale) - spacing * scale


def draw_text(
    target: pygame.Surface,
    text: str,
    x: int,
    y: int,
    scale: int = 1,
    color: tuple[int, int, int] = (235, 232, 242),
    spacing: int = DEFAULT_SPACING,
    shadow: tuple[int, int, int] | None = None,
    shadow_offset: tuple[int, int] = (1, 1),
    alpha: int = 255,
    center: bool = False,
) -> pygame.Rect:
    """Draw uppercase bitmap text and return its bounding rect."""
    text = text.upper()
    width = text_width(text, scale, spacing)
    if center:
        x -= width // 2
    if shadow is not None:
        draw_text(
            target,
            text,
            x + shadow_offset[0] * scale,
            y + shadow_offset[1] * scale,
            scale,
            shadow,
            spacing,
            None,
            alpha=alpha,
        )
    if alpha <= 0:
        return pygame.Rect(x, y, width, GLYPH_H * scale)
    for index, char in enumerate(text):
        glyph = GLYPHS.get(char)
        if glyph is None:
            glyph = GLYPHS["?"]
        base_x = x + index * (GLYPH_W * scale + spacing * scale)
        for row, line in enumerate(glyph):
            for col, bit in enumerate(line):
                if bit == "1":
                    rect = pygame.Rect(
                        base_x + col * scale,
                        y + row * scale,
                        scale,
                        scale,
                    )
                    if alpha >= 255:
                        target.fill(color, rect)
                    else:
                        target.fill((*color, alpha), rect)
    return pygame.Rect(x, y, width, GLYPH_H * scale)
